/** Both dictionaries — exported for the placeholder-parity test. */
export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, gu };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeTranslator(lang: Lang): Translate {
  const table = MESSAGES[lang];
  return (key, vars) => {
    const text = table[key] ?? en[key];
    return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text;
  };
}

/** A menu/category/dish name in the viewer's language, falling back to English. */
export function localName(lang: Lang, name: string, nameGu?: string): string {
  return lang === "gu" && nameGu ? nameGu : name;
}

export function toLang(value: string | undefined): Lang {
  return value === "gu" ? "gu" : "en";
}
